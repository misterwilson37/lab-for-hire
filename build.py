#!/usr/bin/env python3
"""Build everything that is generated from src/.  Run from the repo root.

    python3 build.py                       assemble index.html AND apps-script/LabForHire.gs
    python3 build.py --check               fail if either generated file is stale (someone edited it by hand, or forgot to rebuild)
    python3 build.py --feed-url URL        set the live Sheet address (src/config.json), then build.  --feed-url "" turns it off.

Sources of truth (edit THESE):     src/shell.html  src/engine.js  src/app.js  src/sheet-script.gs  src/config.json
Generated inputs (use the tools):  src/content.json  -> dev/content/embed_content.py      src/art.json -> dev/art/embed_art.py
Generated outputs (never edit):    index.html   apps-script/LabForHire.gs   apps-script/appsscript.json
"""
import json, os, sys
ROOT = os.path.dirname(os.path.abspath(__file__))
def rd(p): return open(os.path.join(ROOT, p), encoding="utf-8").read()
def wr(p, s): os.makedirs(os.path.dirname(os.path.join(ROOT, p)), exist_ok=True); open(os.path.join(ROOT, p), "w", encoding="utf-8", newline="").write(s)

def outputs():
    index = (rd("src/shell.html").replace("/*ART*/", rd("src/art.json")).replace("/*CONFIG*/", rd("src/config.json"))
             .replace("/*CONTENT*/", rd("src/content.json")).replace("/*ENGINE*/", rd("src/engine.js")).replace("/*APP*/", rd("src/app.js")))
    gs = ("/* =====================================================================\n"
          "   LabForHire.gs: GENERATED by build.py. Do not edit this file.\n"
          "   Part 1 is the game's own engine (so the Sheet checks content with the SAME rules the game uses).\n"
          "   Part 2 is the Sheet side: menu, reader, feed. Edit src/sheet-script.gs, then run: python3 build.py\n"
          "   ===================================================================== */\n\n"
          "/* ---------- PART 1: the game engine ---------- */\n" + rd("src/engine.js").strip() + "\n\n"
          "/* ---------- PART 2: the Sheet side ---------- */\n" + rd("src/sheet-script.gs").strip() + "\n")
    manifest = '{\n  "timeZone": "America/Chicago",\n  "dependencies": {},\n  "exceptionLogging": "STACKDRIVER",\n  "runtimeVersion": "V8",\n  "webapp": { "executeAs": "USER_DEPLOYING", "access": "ANYONE_ANONYMOUS" }\n}\n'
    return {"index.html": index, "apps-script/LabForHire.gs": gs, "apps-script/appsscript.json": manifest}

def main(argv):
    if "--feed-url" in argv:
        url = argv[argv.index("--feed-url") + 1] if argv.index("--feed-url") + 1 < len(argv) else ""
        if url and not (url.startswith("https://script.google.com/") and url.rstrip("/").endswith("/exec")):
            sys.exit("That doesn't look like an Apps Script web app address (it should start with https://script.google.com/ and end in /exec).")
        wr("src/config.json", json.dumps({"feedUrl": url})[:0] + '{"feedUrl": %s}' % json.dumps(url))
        print("feed address", "set" if url else "cleared")
    out = outputs()
    if "--check" in argv:
        stale = [p for p, s in out.items() if not os.path.exists(os.path.join(ROOT, p)) or rd(p) != s]
        if stale: sys.exit("STALE (edited by hand, or build.py wasn't run): " + ", ".join(stale) + "\nFix: python3 build.py   (and put any hand edits into src/ instead)")
        print("generated files are up to date: " + ", ".join(out)); return
    for p, s in out.items(): wr(p, s)
    print("built:", ", ".join(f"{p} ({len(s) // 1024} KB)" for p, s in out.items()))
if __name__ == "__main__": main(sys.argv[1:])
